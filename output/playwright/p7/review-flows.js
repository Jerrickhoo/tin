async (page) => {
  const issues = [], errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5195/calendar?month=2026-10');
  await page.getByRole('region', { name: 'Agenda' }).waitFor();
  await page.getByRole('button', { name: /2026-10-22, \d+ items/ }).click();
  const agenda = await page.getByRole('region', { name: 'Agenda' }).innerText();
  if (agenda.includes('Resolved · paid') || !agenda.includes('Due 2026-10-22 · Music subscription')) issues.push('Same-day marker was not collapsed with its source link');
  await page.getByRole('link', { name: 'View these dates in History' }).click();
  await page.getByRole('region', { name: 'Results' }).waitFor();
  const history = await page.getByRole('region', { name: 'Results' }).innerText();
  if (!history.includes('Gross spending ₱1,299.00') || !history.includes('2026-10-22')) issues.push('Calendar/History date or total mismatch');
  await page.goBack();
  await page.getByRole('button', { name: 'Close day' }).waitFor();
  if (!page.url().includes('day=2026-10-22')) issues.push('Back lost selected day');
  await page.getByRole('button', { name: 'Close day' }).click();
  await page.getByLabel('Month', { exact: true }).fill('2027-02');
  await page.getByRole('group', { name: 'February 2027' }).waitFor();
  const futureLink = page.getByRole('region', { name: 'Agenda' }).getByRole('link', { name: 'Music subscription', exact: true });
  const futureHref = await futureLink.getAttribute('href');
  await futureLink.click();
  await page.waitForFunction(() => document.getElementById(location.hash.slice(1))?.open === true);
  if (!page.url().endsWith('2027-02')) issues.push('Future source link lost period');
  await page.goBack();
  await page.getByRole('group', { name: 'February 2027' }).waitFor();
  await page.goto('http://127.0.0.1:5195/insights?month=2026-10');
  await page.getByRole('heading', { name: 'Top categories' }).waitFor();
  await page.getByRole('link', { name: /Bills.*100.0%/ }).click();
  await page.getByRole('region', { name: 'Results' }).waitFor();
  const categoryHistory = await page.getByRole('region', { name: 'Results' }).innerText();
  if (!categoryHistory.includes('Gross spending ₱1,620.09') || !categoryHistory.includes('2026-10-01')) issues.push('Category drilldown not scoped');
  await page.goBack();
  await page.getByText('Details · envelope flows', { exact: true }).click();
  if (!await page.locator('details').evaluate(e => e.open)) issues.push('Details failed');
  await page.context().setOffline(true);
  await page.reload();
  await page.getByRole('heading', { name: 'Current money & commitments' }).waitFor();
  if (!await page.getByText(/Limited data: this device/).isVisible()) issues.push('Offline limited data missing');
  await page.goto('http://127.0.0.1:5195/calendar?month=2026-10&day=2026-10-22');
  await page.getByRole('region', { name: 'Agenda' }).waitFor();
  if (!(await page.getByRole('region', { name: 'Agenda' }).innerText()).includes('₱1,299.00')) issues.push('Offline calendar total changed');
  await page.context().setOffline(false);
  return { passed: !issues.length && !errors.length, issues, errors, futureHref, agenda, history, categoryHistory };
}
